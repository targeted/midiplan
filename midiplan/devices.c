/*
 * Returns true if the note should be routed to the device.
 * It accounts for routing table and bonding configuration.
 */
bool route_note_to_device(
    midi_out_port_t out_port,
    midi_channel_t in_channel,
    program_t in_program,
    note_t in_note
) {

    // static program/note routing table, expressed in input terms

    if (IS_MELODIC_PROGRAM(in_program)) {
        if ((devices[out_port].routing.melodic_programs_bitmap[in_program >> 5] & (1 << (in_program & 0x1F))) == 0) {
            return false;
        }
    }
    else if (IS_PERCUSSION_PROGRAM(in_program)) {
        if ((devices[out_port].routing.percussion_notes_bitmap[in_note >> 5] & (1 << (in_note & 0x1F))) == 0) {
            return false;
        }
    }

    // in case there are several identical devices playing,
    // each could take only a fraction of the programs/notes

    uint8_t device_count = devices[out_port].bonding.device_count;

    if (device_count > 1) {

        uint8_t device_index = devices[out_port].bonding.device_index;

        // the problem that we are trying to solve here is that the same program can be
        // invoked on different input channels, and we would like to have them spread
        // across different bonded devices, thus increasing polyphony and multitimbrality

        // three things to notice here:
        // 1. it often happens that the same input program is played on several input
        //    channels in parallel and we could route those notes to different devices
        // 2. what causes multitimbrality collisions are the *output* programs, because
        //    typically there are multiple input programs mapped to the same output program
        // 3. whether the note is percussion or melodic, is determined in input GM terms,
        //    even though the output note can become the opposite

        uint8_t bonding_key;

        if (IS_MELODIC_PROGRAM(in_program)) {
            bonding_key = bonding_keys[in_channel][in_program >> 1];
            if (in_program & 0x01) { // each random byte contains two random nibbles
                bonding_key &= 0x0F;
            }
            else {
                bonding_key >>= 4;
            }
        }
        else {
            bonding_key = in_note;
        }

        if ((bonding_key % device_count) != device_index) {
            return false;
        }

    }

    return true;

}

