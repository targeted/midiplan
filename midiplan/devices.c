/*
 * The current implementation of bonding is 1 out of N modulo-based,
 * across the namespace of out programs/notes. This can be calculated
 * automatically, knowing what kind of device is on which port.
 * When more than one device of the same type are configured on
 * different ports, they become a single logical device of the same
 * type and each physical device will play only part of the notes.
 * This increases polyphony/multitimbrality automatically.
 * "General MIDI" and "Null" devices are not bonded but will stay
 * segregated and play the same notes.
 */
static void configure_device_order(void) {

    // first, we set up the bonding of identical non-GM-compatible devices

    for (midi_out_port_t i = MIDI_OUT_PORT_1; i < MIDI_OUT_PORT_COUNT; ++i) {
        devices[i].bonding.device_index = 0;
        devices[i].bonding.device_count = 1;
    }

#ifdef TRAINING_MODE

    // in training mode, each device will only receive notes
    // from a single channel, therefore all bonding is ignored

    for (midi_out_port_t i = MIDI_OUT_PORT_1; i < MIDI_OUT_PORT_COUNT; ++i) {
        device_order[i].out_port = i;
        device_order[i].consume_note = true;
    }

#else

    // one edge case is when multiple identical (i.e. bonded) devices have different routing tables,
    // this will result in surprising and unpredictable behavior, when the same note may or may not
    // sound, depending to which device from the set it will be send to, because of this we combine
    // routing tables for all identical bonded device by or-ing them together

    for (midi_out_port_t i = MIDI_OUT_PORT_1; i < MIDI_OUT_PORT_COUNT; ++i) {
        for (midi_out_port_t j = MIDI_OUT_PORT_1; j < MIDI_OUT_PORT_COUNT; ++j) {
            if (
                (i != j) &&
                (devices[j].p_device == devices[i].p_device) &&
                (devices[j].p_device != &gm_device) && // generic devices are segregated
                (devices[j].p_device != &null_device)  // and not automatically bonded
            ) {
                if (i < j) {
                    devices[j].bonding.device_index += 1;
                }
                devices[i].bonding.device_count += 1;

                for (uint8_t k = 0; k < 128 / 32; ++k) {
                    devices[i].routing.melodic_programs_bitmap[k] |= devices[j].routing.melodic_programs_bitmap[k];
                    devices[i].routing.percussion_notes_bitmap[k] |= devices[j].routing.percussion_notes_bitmap[k];
                }
            }
        }
    }

    // now that we know which devices are bonded, we set up their traversal order

    midi_out_port_t i = MIDI_OUT_PORT_1;
    midi_out_port_t j = MIDI_OUT_PORT_1;

    while (i < MIDI_OUT_PORT_COUNT) { // we go from port 1 to port N

        // generic devices are added one by one, marked as not consuming the notes

        if (
            (devices[i].p_device == &gm_device) ||
            (devices[i].p_device == &null_device)
        ) {
            device_order[j].out_port = i;
            device_order[j].consume_note = false;
            j += 1;
            i += 1;
            continue;
        }

        // singular specific devices are also added in order but are marked as consuming the notes

        if (devices[i].bonding.device_count == 1) { // singular device
            device_order[j].out_port = i;
            device_order[j].consume_note = true;
            j += 1;
            i += 1;
            continue;
        }

        // specific devices that appear in more than one instance are bonded and added in one consuming span

        if (devices[i].bonding.device_index > 0) { // the consequent bonded devices must have already been added along with the first one
            i += 1;
            continue;
        }

        evar_assert(i < MIDI_OUT_PORT_COUNT - 1);

        for (midi_out_port_t k = i; k < MIDI_OUT_PORT_COUNT; ++k) {

            if (devices[k].p_device == devices[i].p_device) {
                device_order[j].out_port = k;
                device_order[j].consume_note = true;
                j += 1;
            }
        }

        i += 1;
    }

    evar_assert(j == MIDI_OUT_PORT_COUNT);

#endif

}

void initialize_devices(void) {

    for (midi_out_port_t out_port = MIDI_OUT_PORT_1; out_port < MIDI_OUT_PORT_COUNT; ++out_port) {
        midiplan_device_state_t* p_device_state = &devices[out_port].state;
        initialize_device_state(p_device_state);
    }
}

